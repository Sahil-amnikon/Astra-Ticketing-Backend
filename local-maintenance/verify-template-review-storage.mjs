import fs from 'node:fs';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
const original=fs.readFileSync(process.argv[2],'utf8');
assert.ok(original.includes('CREATE TABLE IF NOT EXISTS change_template_reviews'));
assert.ok(!/\b(?:ALTER|DROP|TRUNCATE|GRANT|REVOKE)\b/i.test(original));
const schema=original.replace(/^\s*KEY [^\n]+\n/gm,'').replaceAll('DATETIME(6)','TEXT').replaceAll('CURRENT_TIMESTAMP(6)','CURRENT_TIMESTAMP').replace(/\)\s*ENGINE=[\s\S]*$/,');');
const db=new DatabaseSync(':memory:');
db.exec(`PRAGMA foreign_keys=ON;
CREATE TABLE users(id CHAR(36) PRIMARY KEY);
CREATE TABLE change_templates(id CHAR(36) PRIMARY KEY);
CREATE TABLE submission_reviews(kind TEXT CHECK(kind IN ('CHANGE','PROBLEM','KNOWLEDGE','SERVICE')),entity_id TEXT);
INSERT INTO users VALUES('author'),('reviewer');
INSERT INTO change_templates VALUES('template');
INSERT INTO submission_reviews VALUES('CHANGE','existing-change');`);
const before=db.prepare('SELECT * FROM submission_reviews').all();
db.exec(schema);
db.exec("INSERT INTO change_template_reviews(kind,entity_id,submitted_by_user_id) VALUES('CHANGE_TEMPLATE','template','author');");
assert.equal(db.prepare('SELECT status FROM change_template_reviews').get().status,'PENDING');
db.exec("UPDATE change_template_reviews SET status='APPROVED',reviewed_by_user_id='reviewer',revision=revision+1 WHERE entity_id='template';");
assert.equal(db.prepare('SELECT status FROM change_template_reviews').get().status,'APPROVED');
assert.throws(()=>db.exec("UPDATE change_template_reviews SET status='UNREVIEWED';"));
assert.throws(()=>db.exec("UPDATE change_template_reviews SET revision=0;"));
assert.throws(()=>db.exec("UPDATE change_template_reviews SET kind='CHANGE';"));
assert.throws(()=>db.exec("INSERT INTO submission_reviews VALUES('CHANGE_TEMPLATE','not-allowed');"));
assert.deepEqual(db.prepare('SELECT * FROM submission_reviews').all(),before);
db.exec("DELETE FROM change_templates WHERE id='template';");
assert.equal(db.prepare('SELECT COUNT(*) AS count FROM change_template_reviews').get().count,0);
assert.deepEqual(db.prepare('SELECT * FROM submission_reviews').all(),before);
db.close();
console.log('PASS: the new template table accepts reviews, enforces its relationships and states, and leaves the original submission table and its constraint intact. SQLite compatibility conversion and invented records only.');
