import {DatabaseSync} from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=fs.readFileSync(path.join(root,'FeatureMultipleTicketUsers.cs'),'utf8');
const contactSql=source.match(/"(SELECT id FROM contacts[^"\n]+)"/)[1].replace(' FOR SHARE','');
const policy=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
const db=new DatabaseSync(':memory:');
db.function('UTC_TIMESTAMP',precision=>'2026-11-19 00:00:00');
db.exec(`CREATE TABLE contacts(id TEXT,client_id TEXT,site_id TEXT,active INTEGER);
CREATE TABLE users(id TEXT,active INTEGER,access_expires_at TEXT);
CREATE TABLE user_roles(user_id TEXT,role_code TEXT);
CREATE TABLE client_users(user_id TEXT,client_id TEXT);
CREATE TABLE user_sites(user_id TEXT,site_id TEXT);
INSERT INTO contacts VALUES('valid','geometry','drinkpak',1),('wrong-client','ravid','drinkpak',1),('wrong-site','geometry','other',1),('inactive','geometry','drinkpak',0);
INSERT INTO users VALUES('technician',1,NULL),('other-team',1,NULL),('disabled',0,NULL),('expired',1,'2020-01-01');
INSERT INTO user_roles VALUES('technician','TECHNICIAN'),('other-team','TECHNICIAN'),('disabled','TECHNICIAN'),('expired','TECHNICIAN');
INSERT INTO client_users VALUES('technician','geometry'),('other-team','ravid'),('disabled','geometry'),('expired','geometry');
INSERT INTO user_sites VALUES('technician','drinkpak');`);
const contacts=db.prepare(contactSql);
for(const contact of ['valid','wrong-client','wrong-site','inactive','missing'])assert.equal(contacts.all({contact,client:'geometry',site:'drinkpak'}).length,contact==='valid'?1:0,contact);
const eligible=db.prepare(`SELECT EXISTS(SELECT 1 FROM users u WHERE u.id=@assignee AND ${policy.active} AND ${policy.scope}) AS allowed`);
for(const assignee of ['technician','other-team','disabled','expired'])assert.equal(eligible.get({assignee,client:'geometry',site:'drinkpak'}).allowed,assignee==='technician'?1:0,assignee);
assert.equal(eligible.get({assignee:'technician',client:'geometry',site:'other'}).allowed,0,'site restriction must apply to automatic assignment');
console.log('PASS: actual contact and assignee SQL rejects other clients, wrong sites, inactive contacts and inactive/expired staff. In-memory fixtures only.');
db.close();
